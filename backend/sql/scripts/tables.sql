CREATE TABLE user_role (
    user_role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_role_name VARCHAR(20) NOT NULL
);

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_first_name VARCHAR(255) NOT NULL,
    user_last_name VARCHAR(255) NOT NULL,
    user_email VARCHAR(255) NOT NULL,
    user_password VARCHAR(255) NOT NULL,
    user_phone_number VARCHAR(20) NOT NULL,
    user_address VARCHAR(255) NOT NULL,
    user_role_id SMALLINT NOT NULL DEFAULT 1 REFERENCES user_role(user_role_id),
    user_discount SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE stock (
    stock_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_name VARCHAR(255) NOT NULL,
    stock_quantity INT NOT NULL,
    stock_threshold INT NOT NULL,
    stock_manager_id BIGINT NOT NULL REFERENCES users(user_id)
);

CREATE TABLE stock_alert (
    stock_alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_alert_message VARCHAR(255) NOT NULL,
    stock_alert_date BIGINT NOT NULL,
    stock_alert_stock_id BIGINT NOT NULL REFERENCES stock(stock_id)
);

CREATE TABLE pizza (
    pizza_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pizza_name VARCHAR(255) NOT NULL,
    pizza_price DECIMAL(6,2) NOT NULL,
    pizza_image_url TEXT NOT NULL
);

CREATE TABLE ingredient (
    ingredient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_name VARCHAR(255) NOT NULL,
    ingredient_updatable SMALLINT NOT NULL,
    ingredient_stock_id BIGINT NOT NULL REFERENCES stock(stock_id)
);

CREATE TABLE pizza_ingredient (
    pizza_ingredient_pizza_id BIGINT NOT NULL REFERENCES pizza(pizza_id),
    pizza_ingredient_ingredient_id BIGINT NOT NULL REFERENCES ingredient(ingredient_id),
    pizza_ingredient_quantity DECIMAL(5,2) NOT NULL,
    PRIMARY KEY (pizza_ingredient_pizza_id, pizza_ingredient_ingredient_id)
);

CREATE TABLE allergen (
    allergen_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    allergen_name VARCHAR(255) NOT NULL
);

CREATE TABLE pizza_allergen (
    pizza_allergen_allergen_id BIGINT NOT NULL REFERENCES allergen(allergen_id),
    pizza_allergen_pizza_id BIGINT NOT NULL REFERENCES pizza(pizza_id),
    PRIMARY KEY (pizza_allergen_allergen_id, pizza_allergen_pizza_id)
);

CREATE TABLE drink (
    drink_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drink_name VARCHAR(255) NOT NULL,
    drink_price DECIMAL(6,2) NOT NULL,
    drink_volume DECIMAL(6,2) NOT NULL,
    drink_image_url TEXT NOT NULL,
    drink_stock_id BIGINT NOT NULL REFERENCES stock(stock_id)
);

CREATE TABLE dessert (
    dessert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dessert_name VARCHAR(255) NOT NULL,
    dessert_price DECIMAL(6,2) NOT NULL,
    dessert_image_url TEXT NOT NULL,
    dessert_stock_id BIGINT NOT NULL REFERENCES stock(stock_id)
);

CREATE TABLE personalization_type (
    personalization_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personalization_type_name VARCHAR(20) NOT NULL
);

CREATE TABLE pizzaiolo (
    pizzaiolo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pizzaiolo_first_name VARCHAR(20) NOT NULL,
    pizzaiolo_last_name VARCHAR(20) NOT NULL
);

CREATE TABLE delivery_man (
    delivery_man_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_man_first_name VARCHAR(20) NOT NULL,
    delivery_man_last_name VARCHAR(20) NOT NULL
);

CREATE TABLE order_state (
    order_state_id SMALLINT PRIMARY KEY,
    order_state_name VARCHAR(20) NOT NULL
);

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_total_price DECIMAL(6,2) NOT NULL,
    order_date BIGINT NOT NULL,
    order_state_id SMALLINT NOT NULL REFERENCES order_state(order_state_id),
    order_user_id BIGINT NOT NULL REFERENCES users(user_id),
    order_pizzaiolo_id BIGINT REFERENCES pizzaiolo(pizzaiolo_id),
    order_delivery_man_id BIGINT REFERENCES delivery_man(delivery_man_id)
);

CREATE TABLE pizza_order (
    pizza_order_order_id BIGINT NOT NULL REFERENCES orders(order_id),
    pizza_order_pizza_id BIGINT NOT NULL REFERENCES pizza(pizza_id),
    pizza_order_quantity INT NOT NULL,
    PRIMARY KEY (pizza_order_order_id, pizza_order_pizza_id)
);

CREATE TABLE drink_order (
    drink_order_order_id BIGINT NOT NULL REFERENCES orders(order_id),
    drink_order_drink_id BIGINT NOT NULL REFERENCES drink(drink_id),
    drink_order_quantity INT NOT NULL,
    PRIMARY KEY (drink_order_order_id, drink_order_drink_id)
);

CREATE TABLE dessert_order (
    dessert_order_order_id BIGINT NOT NULL REFERENCES orders(order_id),
    dessert_order_dessert_id BIGINT NOT NULL REFERENCES dessert(dessert_id),
    dessert_order_quantity INT NOT NULL,
    PRIMARY KEY (dessert_order_order_id, dessert_order_dessert_id)
);

CREATE TABLE custom_pizza_order (
    custom_pizza_order_order_id BIGINT NOT NULL REFERENCES orders(order_id),
    custom_pizza_order_pizza_id BIGINT NOT NULL REFERENCES pizza(pizza_id),
    custom_pizza_order_ingredient_id BIGINT NOT NULL REFERENCES ingredient(ingredient_id),
    custom_pizza_order_personalization_type_id BIGINT NOT NULL REFERENCES personalization_type(personalization_type_id),
    custom_pizza_order_quantity INT NOT NULL,
    PRIMARY KEY (
        custom_pizza_order_order_id,
        custom_pizza_order_pizza_id,
        custom_pizza_order_ingredient_id,
        custom_pizza_order_personalization_type_id
    )
);